  function isDone(lv) {
    if (lv.aim) return aiModules().indexOf(lv.aim) > -1;
    if (!lv.mid) return false;
    try {
      var p = JSON.parse(localStorage.getItem('nooka_profile')) || {};
      return !!(p.missions && p.missions[lv.mid]);
    } catch (e) { return false; }
  }

