/* насколько карта не врёт: совпадает ли ближайший на карте с ближайшим по модели */
function fidelity(P) {
  let hit = 0;
  for (let i = 0; i < N; i++) {
    let bj = -1, bd = Infinity;
    for (let j = 0; j < N; j++) {
      if (i === j) continue;
      const d = Math.hypot(P[i][0] - P[j][0], P[i][1] - P[j][1]);
      if (d < bd) { bd = d; bj = j; }
    }
    if (KIN[i].indexOf(bj) > -1) hit++;
  }
  return hit;
}

